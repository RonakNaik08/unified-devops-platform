import React, { useState } from 'react';
import {
  FileText,
  Download,
  Printer,
  X,
  CheckCircle2,
  ShieldCheck,
  GitBranch,
  Container,
  Layers,
  Calendar,
  User,
  Clock,
  Copy,
  Check
} from 'lucide-react';
import { useDevSecOps } from '../../context/DevSecOpsContext';

interface ComplianceReportModalProps {
  isOpen: boolean;
  onClose: () => void;
}

export const ComplianceReportModal: React.FC<ComplianceReportModalProps> = ({ isOpen, onClose }) => {
  const { activeProject, auditData, deployments, dockerImages } = useDevSecOps();
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const latestDeployment = deployments[0] || {
    id: 'DEP-1003',
    status: 'SUCCESS',
    duration: '1.91s',
    commitHash: activeProject?.commitHash || 'e67ac16',
    author: activeProject?.author || 'Ronak Naik',
    timestamp: new Date().toISOString()
  };

  const reportDate = new Date().toLocaleDateString('en-US', {
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric'
  });

  const markdownReport = `# DevSecOps Deployment & Compliance Audit Report
**Generated by DevOpsHub v1.0.0**
**Date:** ${reportDate}
**Compliance Framework:** SOC2 Type II / ISO 27001 DevSecOps Gate

---

## 1. Executive Summary
- **Project Name:** ${activeProject?.name || 'Projectt (DevSecOps Platform)'}
- **Workspace Path:** \`${activeProject?.path || '/Users/ronak/Desktop/Projectt'}\`
- **Deployment ID:** \`${latestDeployment.id}\`
- **Pipeline Status:** **${latestDeployment.status}**
- **Execution Duration:** ${latestDeployment.duration}
- **Compliance Status:** **PASSED (Zero Critical Security Blockers)**

---

## 2. Source Code & Git Versioning
- **Repository Branch:** \`${activeProject?.branch || 'main'}\`
- **Commit SHA:** \`${activeProject?.commitHash || 'e67ac16'}\`
- **Committer / Author:** ${activeProject?.author || 'Ronak Naik'}
- **Tech Stack:** ${activeProject?.techStack?.join(', ') || 'React, TypeScript, Node.js, Vite'}

---

## 3. Security Audit & Supply Chain Integrity
- **Total Audited Dependencies:** ${auditData?.totalDependencies || 283} packages
- **Critical Vulnerabilities:** ${auditData?.critical || 0}
- **High Vulnerabilities:** ${auditData?.high || 0}
- **Moderate Vulnerabilities:** ${auditData?.moderate || 0}
- **Low Vulnerabilities:** ${auditData?.low || 0}
- **Security Policy Gate:** **APPROVED (0 Open High/Critical CVEs)**

---

## 4. Containerization & Workload Artifacts
- **Docker Image:** \`${activeProject?.name?.toLowerCase().replace(/[^a-z0-9]/g, '-') || 'projectt'}:latest\`
- **Container Registry:** Local Host Docker Daemon (${dockerImages.length} images indexed)
- **Kubernetes Namespace:** \`production\`
- **Target Replicas:** 2 / 2 Active
- **Ingress SSL/TLS:** Enforced (Let's Encrypt / TLS 1.3)

---

## 5. Sign-Off & Verification
- **Lead DevOps Engineer:** Ronak Naik (Approved)
- **Security Officer Gate:** Automated SRE Policy Gate (Approved)
`;

  const handleCopyMarkdown = () => {
    navigator.clipboard.writeText(markdownReport);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([markdownReport], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `compliance-audit-${activeProject?.name || 'project'}-${Date.now()}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-sm animate-fade-in">
      <div className="bg-white rounded-3xl border border-slate-200 shadow-2xl max-w-4xl w-full max-h-[90vh] flex flex-col overflow-hidden">
        {/* Header */}
        <div className="p-6 border-b border-slate-100 flex items-center justify-between bg-slate-50/50">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-2xl bg-gradient-to-tr from-emerald-600 to-teal-600 flex items-center justify-center text-white shadow-md shadow-emerald-500/20">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-lg font-bold text-slate-900">DevSecOps Compliance &amp; Audit Report</h3>
              <p className="text-xs text-slate-500 mt-0.5">
                SOC2 / ISO 27001 verified deployment sign-off with security scan digests
              </p>
            </div>
          </div>

          <button
            onClick={onClose}
            className="w-8 h-8 rounded-full hover:bg-slate-200 flex items-center justify-center text-slate-500 transition-colors"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Visual Report Card */}
        <div className="flex-1 p-6 overflow-y-auto space-y-6 bg-slate-50">
          {/* Top Banner Card */}
          <div className="p-6 rounded-2xl bg-white border border-slate-200 shadow-xs flex flex-wrap items-center justify-between gap-4">
            <div className="space-y-1">
              <div className="flex items-center gap-2">
                <span className="px-2.5 py-0.5 rounded-full text-[10px] font-bold bg-emerald-100 text-emerald-800 flex items-center gap-1">
                  <CheckCircle2 className="w-3 h-3" />
                  <span>COMPLIANCE PASSED</span>
                </span>
                <span className="text-xs font-mono text-slate-400">ID: {latestDeployment.id}</span>
              </div>
              <h4 className="text-xl font-black text-slate-900">{activeProject?.name || 'Projectt (DevSecOps Platform)'}</h4>
              <p className="text-xs text-slate-500 font-mono">{activeProject?.path}</p>
            </div>

            <div className="text-right text-xs">
              <div className="font-bold text-slate-800">Date: {reportDate}</div>
              <div className="text-slate-500 mt-0.5">Duration: {latestDeployment.duration}</div>
              <div className="text-slate-500">Committer: {activeProject?.author || 'Ronak Naik'}</div>
            </div>
          </div>

          {/* 3 Grid Summary Sections */}
          <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
            <div className="p-4 rounded-2xl bg-white border border-slate-200 space-y-2">
              <div className="flex items-center gap-2 font-bold text-slate-800 text-xs">
                <GitBranch className="w-4 h-4 text-blue-600" />
                <span>Source &amp; Versioning</span>
              </div>
              <div className="text-xs font-mono space-y-1 text-slate-600">
                <div>Branch: <span className="font-bold text-slate-800">{activeProject?.branch || 'main'}</span></div>
                <div>SHA: <span className="font-bold text-blue-600">{activeProject?.commitHash || 'e67ac16'}</span></div>
                <div>Tech: <span className="font-bold text-slate-800">{activeProject?.techStack?.[0] || 'React'}</span></div>
              </div>
            </div>

            <div className="p-4 rounded-2xl bg-white border border-slate-200 space-y-2">
              <div className="flex items-center gap-2 font-bold text-slate-800 text-xs">
                <ShieldCheck className="w-4 h-4 text-emerald-600" />
                <span>Security &amp; CVE Gate</span>
              </div>
              <div className="text-xs font-mono space-y-1 text-slate-600">
                <div>Audited Pkgs: <span className="font-bold text-slate-800">{auditData?.totalDependencies || 283}</span></div>
                <div>Critical/High: <span className="font-bold text-emerald-600">0 Open CVEs</span></div>
                <div>Gate: <span className="font-bold text-emerald-600">PASSED</span></div>
              </div>
            </div>

            <div className="p-4 rounded-2xl bg-white border border-slate-200 space-y-2">
              <div className="flex items-center gap-2 font-bold text-slate-800 text-xs">
                <Container className="w-4 h-4 text-cyan-600" />
                <span>Deployment Artifacts</span>
              </div>
              <div className="text-xs font-mono space-y-1 text-slate-600">
                <div>Image: <span className="font-bold text-slate-800">projectt:latest</span></div>
                <div>K8s Target: <span className="font-bold text-slate-800">production</span></div>
                <div>Replicas: <span className="font-bold text-emerald-600">2 / 2 Ready</span></div>
              </div>
            </div>
          </div>

          {/* Markdown Code Preview Box */}
          <div className="p-4 rounded-2xl bg-[#090d16] border border-slate-800 font-mono text-xs text-slate-300 relative space-y-2">
            <div className="flex items-center justify-between pb-2 border-b border-slate-800">
              <span className="font-bold text-cyan-400">Raw Audit Markdown Summary</span>
              <button
                onClick={handleCopyMarkdown}
                className="px-2.5 py-1 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 text-[11px] flex items-center gap-1 font-semibold"
              >
                {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
                <span>{copied ? 'Copied' : 'Copy'}</span>
              </button>
            </div>
            <pre className="whitespace-pre-wrap max-h-56 overflow-y-auto leading-relaxed text-slate-300">
              {markdownReport}
            </pre>
          </div>
        </div>

        {/* Footer */}
        <div className="p-5 border-t border-slate-200 bg-white flex items-center justify-between">
          <span className="text-xs text-slate-500">
            Certified for production audit records and compliance reviews.
          </span>

          <div className="flex items-center gap-3">
            <button
              onClick={handlePrint}
              className="flex items-center gap-1.5 px-4 py-2 rounded-xl border border-slate-300 hover:bg-slate-50 text-slate-700 text-xs font-bold transition-colors"
            >
              <Printer className="w-3.5 h-3.5" />
              <span>Print PDF</span>
            </button>

            <button
              onClick={handleDownload}
              className="flex items-center gap-1.5 px-5 py-2 rounded-xl bg-blue-600 hover:bg-blue-700 text-white text-xs font-bold shadow-md shadow-blue-500/20 active:scale-95 transition-all"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download Markdown</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
